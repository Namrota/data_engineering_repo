
-- Check your current Snowflake context
SELECT
    CURRENT_USER(),
    CURRENT_ROLE(),
    CURRENT_WAREHOUSE();

-- Create the database
CREATE DATABASE IF NOT EXISTS KAFKA_DEMO;

-- Create the schema
CREATE SCHEMA IF NOT EXISTS KAFKA_DEMO.REALTIME;

-- Select the database and schema
USE DATABASE KAFKA_DEMO;
USE SCHEMA REALTIME;

-- Create the orders table
CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID NUMBER(19,0),
    CUSTOMER_NAME VARCHAR(200),
    CITY VARCHAR(100),
    PRODUCT VARCHAR(100),
    AMOUNT NUMBER(12,2),
    PAYMENT_MODE VARCHAR(100),
    ORDER_TIME TIMESTAMP_NTZ,
    INGESTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Verify if the table exists
SELECT * FROM orders;


-- After connecting the snowflake as the consumer:
SELECT
    COUNT(*) AS TOTAL_ORDERS,
    COUNT(DISTINCT ORDER_ID) AS UNIQUE_ORDERS,
    SUM(AMOUNT) AS TOTAL_REVENUE
FROM KAFKA_DEMO.REALTIME.ORDERS;


SELECT *
FROM KAFKA_DEMO.REALTIME.ORDERS
ORDER BY ORDER_TIME;